def save_config(num_processes, num_threads_per_process, gpu_ram_gb):
    """
    Save server configuration to a JSON file that classify.py can read.
    This allows classify.py to know how many threads to use.
    """
    config = {
        "timestamp": time.time(),
        "num_processes": num_processes,
        "num_threads_per_process": num_threads_per_process,
        "gpu_ram_gb": gpu_ram_gb,
        "notes": "This file is auto-generated by run_server.py. You can manually edit num_threads_per_process.",
    }
    try:
        with open(CONFIG_FILE, "w") as f:
            json.dump(config, f, indent=2)
        print(f"✅ Configuration saved to '{CONFIG_FILE}'")
    except IOError as e:
        print(f"⚠️  Could not write config file: {e}")


def load_config():
    """Load configuration from file."""
    if not os.path.exists(CONFIG_FILE):
        return None
    try:
        with open(CONFIG_FILE, "r") as f:
            return json.load(f)
    except (json.JSONDecodeError, IOError):
        return None


