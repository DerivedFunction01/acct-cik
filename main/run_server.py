if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Manage FastAPI servers with automatic model-based process spawning.",
        formatter_class=argparse.RawTextHelpFormatter,
    )
    parser.add_argument(
        "action",
        nargs="?",
        default=None,
        choices=["start", "stop", "restart", "status", "clear-cache"],
        help="""
start       - Start the FastAPI and Nginx servers.
stop        - Stop all running servers.
restart     - Stop and then start all servers.
status      - Check if the servers are running.
clear-cache - Clear the cached system information.
""",
    )

    args = parser.parse_args()
    action = args.action

    if action is None:
        if os.path.exists(PID_FILE):
            print("ℹ️ Servers appear to be running. Stopping them now.")
            stop_servers()
        else:
            print("ℹ️ Servers appear to be stopped. Starting them now.")
            start_servers()
    elif action == "start":
        start_servers()
    elif action == "stop":
        stop_servers()
    elif action == "restart":
        stop_servers()
        print("\nRestarting in 3 seconds...")
        time.sleep(3)
        start_servers()
    elif action == "status":
        if os.path.exists(PID_FILE):
            print("✅ Servers appear to be RUNNING.")
        else:
            print("❌ Servers appear to be STOPPED.")
    elif action == "clear-cache":
        if os.path.exists(CACHE_FILE):
            os.remove(CACHE_FILE)
            print("✅ Cache cleared.")
        if os.path.exists(CONFIG_FILE):
            os.remove(CONFIG_FILE)
            print("✅ Config cleared.")
        else:
            print("ℹ️ No cache/config files found.")
