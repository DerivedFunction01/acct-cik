MODEL_PATH = "DerivedFunction/Qwen3-1.7B-derivatives-classifier"
MODEL_SIZE_GB = 3.5  # Approximate size of the loaded model (3-4GB)
ESTIMATED_OVERHEAD_GB = 1.0  # Memory overhead per process

# Server ports
NGINX_PORT = 5000
BASE_GPU_SERVER_PORT = 5001

# File paths
PID_FILE = "server.pid"
NGINX_CONF_FILE = "nginx.conf"
SERVER_SCRIPT = "server:app"
CACHE_FILE = ".server_cache.json"
CONFIG_FILE = ".server_config.json"  # NEW: Config file for classify.py

# Gunicorn settings
GUNICORN_TIMEOUT = 120

